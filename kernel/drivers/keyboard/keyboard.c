void irq_handler_keyboard(void){
    uint8_t scanByte = inb(0x60);
    
    if(!(scanByte & (0x80))){        
        vga_put_char(code_to_ascii[scanByte]);
    }
    
    pic_send_eoi(1);
    return;
}